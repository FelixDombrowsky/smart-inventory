//
// วิธีเพิ่มภาษาใหม่: เพิ่ม key ภาษาใหม่ (เช่น "ja") เป็น object ใหม่ในทุก dict (NAV_LABELS, DASHBOARD_LABELS, ...) ให้มี key ครบเหมือน en/th
// วิธีเพิ่มเมนูใหม่ใน nav bar: เพิ่ม key ให้ตรงกับ id ของ <li>/<a> ใน _Layout.cshtml (ดู NAV_PAIRS ใน _Layout.cshtml) ในทุกภาษาที่มี
//
// วิธีเพิ่มคำแปลของหน้าใหม่ (นอกเหนือจาก nav bar):
//   1. เพิ่ม dict ใหม่ในไฟล์นี้ (เช่น const LOTS_LABELS = { en: {...}, th: {...} }) ให้ key ตรงกันทั้ง en/th
//   2. ในหน้านั้น ใส่ attribute data-i18n="ชื่อ key" บน element ที่ต้องการแปล textContent
//      (หรือ data-i18n-placeholder="..." สำหรับ input placeholder, data-i18n-title="..." สำหรับ title/tooltip)
//   3. เรียก applyDataI18n(LOTS_LABELS[getCurrentLang()]) ตอน init ของหน้า
//   4. ถ้าหน้านั้นมีเนื้อหาที่ render ผ่าน JS (เช่น table row, badge ข้อความ) ต้องดึงคำจาก dict เอง (ไม่ใช้ data-i18n เพราะไม่มี element ตายตัว)
//      แล้ว re-render ใหม่ตอนเปลี่ยนภาษา — ประกาศ window.onLangChange = function(lang) { ... } ไว้ในหน้านั้น
//      _Layout.cshtml (applyLang) จะเรียก window.onLangChange(lang) ให้เองทุกครั้งที่กดปุ่มเปลี่ยนภาษา ถ้าหน้านั้นประกาศไว้

// ภาษาปัจจุบันที่ user เลือกไว้ (ไม่ต้องรอ _Layout.cshtml init เพราะอ่านจาก localStorage ตรงๆ) — ใช้ตอนหน้าไหนๆ init ครั้งแรกก็ได้
function getCurrentLang() {
    try { return localStorage.getItem('sf_lang') || 'en' } catch (_) { return 'en' }
}

// เดิน element ทุกตัวที่มี data-i18n / data-i18n-placeholder / data-i18n-title แล้วเซ็ตค่าจาก dict ที่ส่งมา (ใช้ร่วมกันได้ทุกหน้า)
// key ที่ไม่มีใน dict จะถูกข้ามไปเฉยๆ (เผื่อ element ค้างจาก dict เก่า) ไม่ throw error
function applyDataI18n(dict) {
    if (!dict) return
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const val = dict[el.dataset.i18n]
        if (val !== undefined) el.textContent = val
    })
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const val = dict[el.dataset.i18nPlaceholder]
        if (val !== undefined) el.placeholder = val
    })
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const val = dict[el.dataset.i18nTitle]
        if (val !== undefined) el.title = val
    })
}

